"""Compare all decision modes on matched seeds and a seeded surge scenario."""

from pathlib import Path
import sys
import time

import pandas as pd
import plotly.express as px

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backend.simulation.engine import Disruption, HospitalSimulation

SCENARIOS = {
    "admission_surge": ("surge", None, 0.3),
    "nurse_shortage": ("nurse_unavailable", "General Medicine", 0.3),
    "bed_closure": ("bed_closure", "Cardiology", 0.3),
    "ed_overload": ("ed_overload", None, 0.5),
}


def run(seeds: list[int] | None = None, horizon: int = 72) -> pd.DataFrame:
    rows = []
    for seed in seeds or [11, 23, 42]:
        for scenario_name, (kind, department, magnitude) in SCENARIOS.items():
            for mode in ("predictive", "quantum", "hybrid"):
                simulation = HospitalSimulation(seed=seed, horizon=horizon, mode=mode)
                if horizon > 24:
                    simulation.events.append(Disruption(kind, department, 24, min(12, horizon - 24), magnitude))
                started = time.perf_counter()
                for _ in range(horizon):
                    simulation.step()
                records = simulation.history
                rows.append({
                    "seed": seed, "scenario": scenario_name, "mode": mode, "horizon": horizon,
                    "bed_utilization": sum(r["utilization"] for r in records) / horizon,
                    "unmet_demand_total": sum(r["unmet_demand"] for r in records),
                    "final_unmet_demand": records[-1]["unmet_demand"],
                    "nurse_balance": sum(r["nurse_balance"] for r in records) / horizon,
                    "optimizer_ms_mean": sum(r["optimizer_ms"] for r in records) / horizon,
                    "forecast_mae": sum(r["forecast_mae"] for r in records) / horizon,
                    "forecast_rmse": sum(r["forecast_rmse"] for r in records) / horizon,
                    "forecast_mape": sum(r["forecast_mape"] for r in records) / horizon,
                    "allocation_quality": sum(r["allocation_quality"] for r in records) / horizon,
                    "recovery_time_hours": max((r["recovery_time_hours"] for r in records), default=-1),
                    "runtime_s": time.perf_counter() - started,
                })
    return pd.DataFrame(rows)


if __name__ == "__main__":
    output = Path("results")
    output.mkdir(exist_ok=True)
    results = run()
    results.to_csv(output / "mode_comparison.csv", index=False)
    figure = px.box(results, x="mode", y="unmet_demand_total", color="scenario", title="Unmet demand by mode and disruption scenario")
    figure.write_html(output / "mode_comparison.html")
    summary = results.groupby("mode")[["bed_utilization", "unmet_demand_total", "final_unmet_demand", "nurse_balance", "optimizer_ms_mean", "forecast_mae", "forecast_rmse", "forecast_mape", "allocation_quality", "recovery_time_hours", "runtime_s"]].mean().round(3)
    best_queue = summary["unmet_demand_total"].idxmin()
    slowest_solver = summary["optimizer_ms_mean"].idxmax()
    (output / "SUMMARY.md").write_text(
        "# Experimental Results\n\n"
        "Generated by `scripts/run_experiments.py` from matched seeded synthetic scenarios. "
        "These results describe this simulator only and are not clinical evidence.\n\n"
        f"Across {results.seed.nunique()} seeds, {results.scenario.nunique()} disruption scenarios, and a {int(results.horizon.iloc[0])}-hour horizon, "
        f"`{best_queue}` had the lowest mean cumulative unmet-demand measure "
        f"({summary.loc[best_queue, 'unmet_demand_total']:.3f}). "
        f"`{slowest_solver}` had the highest mean solver time "
        f"({summary.loc[slowest_solver, 'optimizer_ms_mean']:.3f} ms per step). "
        "This is a small synthetic benchmark; no causal or clinical generalization is justified.\n\n"
        + "```text\n" + summary.to_string() + "\n```\n\n"
        "Solver timings include local process overhead and are not a hardware-accelerator benchmark. "
        "No quantum advantage is claimed.\n",
        encoding="utf-8",
    )
    print(summary.to_string())